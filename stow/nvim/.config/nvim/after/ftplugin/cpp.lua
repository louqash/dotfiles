-- 2-space indentation for C++ (overrides the global 4-space default in set.lua).
-- Buffer-local via opt_local so other filetypes keep 4 spaces.
-- Covers .cpp/.cc/.cxx and the .hpp/.hh/.hxx headers (all filetype=cpp).
vim.opt_local.tabstop = 2
vim.opt_local.softtabstop = 2
vim.opt_local.shiftwidth = 2
vim.opt_local.expandtab = true
